/**
 * Regenerates src/lib/workflow-viewer/onboarding.generated.ts and the Mermaid and JSON blocks in
 * content/docs/guides/view-email-workflows.mdx from the onboarding example. The viewer hydrates on
 * the client, so it reads this snapshot instead of running the engine in the browser, and the
 * page's .md twin carries the same Mermaid and JSON an agent would get from the CLI.
 *
 * Run with: bun run workflow-viewer:generate (from apps/fumadocs). `--check` fails on drift.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

import { buildOnboardingViewerData } from "../src/lib/workflow-viewer/build";

const root = resolve(import.meta.dir, "..");

const dataPath = join(root, "src/lib/workflow-viewer/onboarding.generated.ts");

const pagePath = join(root, "content/docs/guides/view-email-workflows.mdx");

const check = process.argv.includes("--check");

const data = await buildOnboardingViewerData();

const module = `// Generated by scripts/generate-workflow-viewer.ts from onboarding-workflow.ts. Do not edit.
import type { WorkflowViewerData } from "./types";

export const onboardingViewerData: WorkflowViewerData = ${JSON.stringify(data, null, 2)};
`;

function replaceBlock(source: string, name: string, language: string, body: string) {
  const pattern = new RegExp(`(\\{/\\* generated:${name} \\*/\\}\\n)\`\`\`${language}\\n(?:[\\s\\S]*?\\n)??\`\`\``);

  if (!pattern.test(source)) throw new Error(`${pagePath} is missing the generated:${name} block.`);

  return source.replace(pattern, (_match, marker: string) => `${marker}\`\`\`${language}\n${body}\n\`\`\``);
}

const page = readFileSync(pagePath, "utf8");

const dayTwo = data.frames[1]?.timeline;

if (!dayTwo) throw new Error("The sample run has no day-2 frame.");

const nextPage = [
  ["mermaid", "mermaid", data.mermaid],
  ["timeline", "json", JSON.stringify(dayTwo, null, 2)],
  ["json", "json", JSON.stringify(data.graph, null, 2)],
].reduce((source, [name = "", language = "", body = ""]) => replaceBlock(source, name, language, body), page);

const stale = [
  existsSync(dataPath) && readFileSync(dataPath, "utf8") === module ? undefined : dataPath,
  page === nextPage ? undefined : pagePath,
].filter((path) => path !== undefined);

if (check) {
  if (stale.length > 0) {
    console.error(`Workflow viewer snapshot is stale: ${stale.join(", ")}. Run bun run workflow-viewer:generate.`);
    process.exit(1);
  }

  console.log("Workflow viewer snapshot is current.");
} else {
  writeFileSync(dataPath, module);
  writeFileSync(pagePath, nextPage);
  console.log(`Wrote ${data.graph.nodes.length} nodes and ${data.frames.length} frames.`);
}
