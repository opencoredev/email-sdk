// Writes the /compare pages as MDX content from lib/compare.ts, so every pair
// gets Blume's sitemap entry, search record, Markdown mirror, and llms.txt
// line. The data stays the source of truth: edit lib/compare.ts, then run
// `bun run compare:generate`. `--check` fails when a page is stale.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import {
  type ComparePair,
  comparePairLastmod,
  comparePairs,
  getComparePairTitle,
  getFallbackGaps,
  getFieldSupport,
  getProvider,
  getProviderBlogGuides,
  messageFieldLabels,
  messageFields,
  type ProviderKey,
} from "../lib/compare";
import {
  buildCompareDescription,
  buildCompareFaq,
  buildComparePageTitle,
  fallbackSnippet,
  listFields,
  sendSnippet,
} from "../lib/compare-page";
import { providers } from "../lib/providers";

const outputDir = join(import.meta.dirname, "../content/compare");

const check = process.argv.includes("--check");

const header =
  "{/* Generated by scripts/generate-compare-pages.ts from lib/compare.ts. Do not edit. */}";

// The four providers people most often weigh together; every pair among them
// has its own page.
const bigFourSlugs = new Set([
  "resend-vs-sendgrid",
  "resend-vs-postmark",
  "resend-vs-mailgun",
  "postmark-vs-sendgrid",
  "postmark-vs-mailgun",
  "sendgrid-vs-mailgun",
]);

/** Escape prose for MDX: braces and `<` would otherwise start JSX. */
function prose(text: string) {
  return text.replaceAll("{", "\\{").replaceAll("}", "\\}").replaceAll("<", "&lt;");
}

function yaml(text: string) {
  return JSON.stringify(text);
}

function mark(key: ProviderKey, field: (typeof messageFields)[number]) {
  return getFieldSupport(key)[field] === true ? "✓" : "—";
}

function pairPage(pair: ComparePair, order: number) {
  const a = getProvider(pair.a);
  const b = getProvider(pair.b);
  const title = getComparePairTitle(pair);
  const gapsAtoB = getFallbackGaps(pair.a, pair.b);
  const gapsBtoA = getFallbackGaps(pair.b, pair.a);

  const table = [
    `| Message field | ${a.name} | ${b.name} |`,
    "| --- | :---: | :---: |",
    ...messageFields.map(
      (field) =>
        `| ${messageFieldLabels[field]} | ${mark(pair.a, field)} | ${mark(pair.b, field)} |`,
    ),
  ].join("\n");

  const fallback =
    gapsAtoB.length === 0 && gapsBtoA.length === 0
      ? `${a.name} and ${b.name} support identical message fields, so Email SDK can fail over between them in either direction without losing data.`
      : [
          gapsAtoB.length > 0
            ? `Failing over from **${a.name}** to **${b.name}** loses: ${listFields(gapsAtoB)}. Email SDK rejects the fallback send for messages that use these fields instead of dropping them silently.`
            : undefined,
          gapsBtoA.length > 0
            ? `Failing over from **${b.name}** to **${a.name}** loses: ${listFields(gapsBtoA)}.`
            : undefined,
        ]
          .filter(Boolean)
          .join("\n\n");

  const guides = getProviderBlogGuides(pair)
    .map((guide) => `${prose(guide.lead)} Read the [${prose(guide.title)}](/blog/${guide.slug}).`)
    .join("\n\n");

  const frontmatter = [
    `title: ${yaml(title)}`,
    `description: ${yaml(buildCompareDescription(pair))}`,
    "seo:",
    `  title: ${yaml(buildComparePageTitle(pair))}`,
    `  image: /images/og/compare/${pair.slug}.png`,
    "sidebar:",
    `  order: ${order}`,
    `lastModified: ${comparePairLastmod(pair)}`,
  ];

  return `---
${frontmatter.join("\n")}
---

${header}

${pair.search ? `**Short answer:** ${prose(pair.search.verdict)}\n\n` : ""}${prose(pair.intro)}

## Message field support

Field support as encoded in Email SDK's own adapter capability matrix, the same data the SDK uses to reject sends that would silently drop fields.

${table}

## Fallback compatibility

${prose(fallback)}

## Same code, either provider

With Email SDK the send call is identical for both providers. Only the adapter import changes:

\`\`\`ts
${sendSnippet(pair.a, a.importPath)}
\`\`\`

Or run both, with automatic fallback:

\`\`\`ts
${fallbackSnippet(pair, a.importPath, b.importPath)}
\`\`\`

## FAQ

${buildCompareFaq(pair)
  .map((entry) => `### ${prose(entry.question)}\n\n${prose(entry.answer)}`)
  .join("\n\n")}

## Adapter docs

Setup guides: [${a.name} adapter](${a.docs}) and [${b.name} adapter](${b.docs}). Sending from your own domain? Verify SPF, DKIM, and DMARC with the free [email DNS checker](/tools/email-dns-checker).
${guides ? `\n${guides}\n` : ""}`;
}

function indexPage() {
  const bigFour = comparePairs.filter((pair) => bigFourSlugs.has(pair.slug));

  const bigFourLinks = bigFour.map(
    (pair) => `[${getComparePairTitle(pair)}](/compare/${pair.slug})`,
  );

  const bigFourSentence = `${bigFourLinks.slice(0, -1).join(", ")}, and ${bigFourLinks.at(-1)}`;

  const matrix = [
    `| Provider | ${messageFields.join(" | ")} |`,
    `| --- | ${messageFields.map(() => ":---:").join(" | ")} |`,
    ...providers.map(
      (provider) =>
        `| ${provider.name} | ${messageFields.map((field) => mark(provider.key, field)).join(" | ")} |`,
    ),
  ].join("\n");

  return `---
title: Compare transactional email providers
description: "Compare Resend, SendGrid, Postmark, Mailgun, Amazon SES, Brevo and more side by side: which message fields each email API supports and what survives a switch."
seo:
  title: "Email API Comparison: Resend, SendGrid, Postmark, Mailgun"
sidebar:
  label: Overview
  icon: git-compare-arrows
---

${header}

These comparisons are generated from Email SDK's own adapter capability matrix: the field-support data the SDK uses to fail fast instead of silently dropping CC recipients, attachments, or metadata. Every provider below works behind the same typed \`send()\` call.

Choosing between Resend, SendGrid, Postmark, and Mailgun? Each pair has its own page: ${bigFourSentence}.

## Head-to-head comparisons

${comparePairs.map((pair) => `- [${getComparePairTitle(pair)}](/compare/${pair.slug})`).join("\n")}

## Full capability matrix

Message-field support across all ${providers.length} adapters, straight from the SDK source. See the [field support docs](/docs/adapters/field-support) for what each field means.

${matrix}
`;
}

const expected = new Map<string, string>([["index.mdx", indexPage()]]);

comparePairs.forEach((pair, index) => expected.set(`${pair.slug}.mdx`, pairPage(pair, index + 1)));

let stale = 0;

if (!check) mkdirSync(outputDir, { recursive: true });

for (const [file, content] of expected) {
  const path = join(outputDir, file);
  const current = existsSync(path) ? readFileSync(path, "utf8") : undefined;

  if (current === content) continue;

  stale += 1;

  if (check) console.error(`[compare] stale: content/compare/${file}`);
  else writeFileSync(path, content);
}

for (const file of existsSync(outputDir) ? readdirSync(outputDir) : []) {
  if (file.endsWith(".mdx") && !expected.has(file)) {
    stale += 1;

    if (check) console.error(`[compare] unexpected: content/compare/${file}`);
    else rmSync(join(outputDir, file));
  }
}

if (check && stale > 0) {
  console.error("[compare] run `bun run compare:generate` and commit the result.");
  process.exit(1);
}

console.log(check ? "[compare] pages are current" : `[compare] wrote ${stale} page(s)`);
