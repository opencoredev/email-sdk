// Writes the "Frequently asked questions" section at the end of every adapter
// page from lib/adapter-faq.ts, so the answers follow the support data and
// still render, search, and appear in the Markdown mirror like any other
// heading. The section sits between two marker comments; everything outside
// them is hand-written. `--check` fails when a page is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { buildAdapterFaq } from "../lib/adapter-faq";
import { ADAPTER_SUPPORT_ENTRIES } from "../lib/adapter-support";

const adaptersDir = join(import.meta.dirname, "../content/docs/adapters");

const start = "{/* adapter-faq:start (generated by scripts/generate-adapter-faq.ts) */}";

const end = "{/* adapter-faq:end */}";

const check = process.argv.includes("--check");

/** Escape prose for MDX: braces and `<` would otherwise start JSX. */
function prose(text: string) {
  return text.replaceAll("{", "\\{").replaceAll("}", "\\}").replaceAll("<", "&lt;");
}

let stale = 0;

for (const entry of ADAPTER_SUPPORT_ENTRIES) {
  const file = join(adaptersDir, `${entry.id}.mdx`);
  const current = readFileSync(file, "utf8");

  const section = [
    start,
    "",
    "## Frequently asked questions",
    "",
    ...buildAdapterFaq(entry).flatMap((item) => [
      `### ${prose(item.question)}`,
      "",
      prose(item.answer),
      "",
    ]),
    end,
  ].join("\n");

  const startIndex = current.indexOf(start);
  const endIndex = current.indexOf(end);

  const body =
    startIndex === -1 || endIndex === -1
      ? current.trimEnd()
      : `${current.slice(0, startIndex).trimEnd()}${current.slice(endIndex + end.length).trimEnd()}`;

  const next = `${body}\n\n${section}\n`;

  if (next === current) continue;

  stale += 1;

  if (check) console.error(`[adapter-faq] stale: content/docs/adapters/${entry.id}.mdx`);
  else writeFileSync(file, next);
}

if (check && stale > 0) {
  console.error("[adapter-faq] run `bun run adapter-faq:generate` and commit the result.");
  process.exit(1);
}

console.log(
  check ? "[adapter-faq] adapter pages are current" : `[adapter-faq] updated ${stale} page(s)`,
);
